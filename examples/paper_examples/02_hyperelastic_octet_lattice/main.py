"""Compute the finite-strain response of imperfect Octet cells.

The primitive cell and, optionally, a 2 x 2 x 2 supercell are perturbed
along their first modes generated by ``buckling.py``. Compression, tension,
and simple shear are then applied to 40 percent macroscopic deformation
using quasi-static implicit dynamics.
"""

import os
import sys

import gmsh
import numpy as np
from abaqusConstants import (ISOTROPIC, NEO_HOOKE, OFF, ON, QUASI_STATIC,
                             VOLUMETRIC_DATA)
from octet import apply_eigenmode_imperfection, create_geometry

from abqhom.abqmodel import AbaqusRVE, LoadHistory
from abqhom.gmshmodel import GmshRVE
from abqhom.utils import export_to_csv_file, hill_mandel_residual

here = os.getcwd()


def assign_section(cell, radius, youngs_modulus, poissons_ratio, density):
    """Assign a compressible Neo-Hookean circular beam section."""
    c10 = youngs_modulus / (4.0 * (1.0 + poissons_ratio))
    d1 = 6.0 * (1.0 - 2.0 * poissons_ratio) / youngs_modulus

    material = cell.model.Material(name="OCTET_MATERIAL")
    material.Hyperelastic(
        materialType=ISOTROPIC, testData=OFF, type=NEO_HOOKE,
        volumetricResponse=VOLUMETRIC_DATA, table=((c10, d1),))
    material.Density(table=((density,),))
    cell.assign_beam_section(
        "OCTET_BEAMS", "OCTET_MATERIAL", radius, pre_integrate=False)


def maximum_rotation(cell, step_name):
    """Return the maximum nodal rotation-vector magnitude over all frames."""
    cell.open_odb_file()
    try:
        instance = cell.odb.rootAssembly.instances[cell.model_name]
        maximum = 0.0
        for frame in cell.odb.steps[step_name].frames:
            values = frame.fieldOutputs["UR"].getSubset(
                region=instance).values
            for value in values:
                magnitude = np.linalg.norm(
                    np.asarray(value.data, dtype=float))
                maximum = max(maximum, magnitude)
        return maximum
    finally:
        cell.close_odb_file()


def energy_ratios(cell, step_name, minimum_pseudo_time=0.02):
    """Return kinetic-to-internal-energy ratios for one analysis."""
    cell.open_odb_file()
    try:
        step = cell.odb.steps[step_name]
        region_name = "Assembly ASSEMBLY"
        if region_name not in step.historyRegions:
            raise RuntimeError(
                "The assembly energy-history region is unavailable.")
        outputs = step.historyRegions[region_name].historyOutputs
        if "ALLIE" not in outputs or "ALLKE" not in outputs:
            raise RuntimeError("ALLIE and ALLKE are unavailable in the ODB.")

        internal = dict(outputs["ALLIE"].data)
        kinetic = dict(outputs["ALLKE"].data)
        records = [(time, internal[time], kinetic[time])
                   for time in sorted(set(internal) & set(kinetic))]
        ratios = [(time, abs(ke) / max(abs(ie), 1.0e-30))
                  for time, ie, ke in records
                  if time >= minimum_pseudo_time]
        if not ratios:
            raise RuntimeError(
                "No energy data are available after pseudo-time {}."
                .format(minimum_pseudo_time))

        peak_time, peak_ratio = max(ratios, key=lambda item: item[1])
        maximum_kinetic = max(abs(ke) for _, _, ke in records)
        maximum_internal = max(abs(ie) for _, ie, _ in records)
        ratio_of_maxima = maximum_kinetic / maximum_internal
        return {
            "peak_ratio": peak_ratio,
            "peak_time": peak_time,
            "final_ratio": ratios[-1][1],
            "ratio_of_maxima": ratio_of_maxima,
        }
    finally:
        cell.close_odb_file()


def evaluate_response(cell, step_name, load_path, component,
                      power_tolerance):
    """Evaluate effective stresses and discrete Hill--Mandel residuals."""
    response = []
    cell.open_odb_file()
    try:
        step = cell.odb.steps[step_name]
        previous_gradient = None
        for frame_index, frame in enumerate(step.frames):
            gradient = load_path(frame.frameValue)
            deformation_gradient = np.eye(3) + gradient
            nominal_stress = cell.average_stress(
                step_name, frame=frame_index)

            # Push the effective first Piola--Kirchhoff stress forward to
            # the effective Cauchy stress at the current macroscopic state.
            jacobian = np.linalg.det(deformation_gradient)
            cauchy_stress = (nominal_stress.dot(
                deformation_gradient.T) / jacobian)
            scale = max(np.linalg.norm(cauchy_stress), 1.0e-30)
            asymmetry = (np.linalg.norm(
                cauchy_stress - cauchy_stress.T) / scale)

            hill_mandel = np.nan
            if previous_gradient is not None:
                # Insert the increment between successive converged frames
                # as the common macroscopic and microscopic test direction.
                increment = gradient - previous_gradient
                macroscopic_work = float(np.sum(nominal_stress * increment))
                microscopic_work = cell.average_power_increment(
                    step_name, frame=frame_index)
                hill_mandel = hill_mandel_residual(
                    macroscopic_work, microscopic_work, power_tolerance)

            response.append(np.concatenate((
                [frame.frameValue, deformation_gradient[component]],
                nominal_stress.reshape(-1), cauchy_stress.reshape(-1),
                [asymmetry, hill_mandel])))
            previous_gradient = gradient
    finally:
        cell.close_odb_file()

    return np.asarray(response)


def export_results(result_directory, response, component, energies,
                   rotation):
    """Export the response curves and verification measures of one case."""
    if not os.path.isdir(result_directory):
        os.makedirs(result_directory)

    # Columns: pseudo-time, loading measure, P (9), sigma (9), asymmetry,
    # and Hill--Mandel residual
    components = ("11", "12", "13", "21", "22", "23", "31", "32", "33")
    response_header = ",".join(
        ("pseudo_time", "loading_measure")
        + tuple("P_" + name for name in components)
        + tuple("sigma_" + name for name in components)
        + ("stress_asymmetry", "hill_mandel_residual"))
    export_to_csv_file(
        response, os.path.join(result_directory, "full_response"),
        header=response_header)

    stress_index = 3 * component[0] + component[1]
    curve = np.column_stack((
        response[:, 1], response[:, 2 + stress_index],
        response[:, 11 + stress_index]))
    export_to_csv_file(
        curve, os.path.join(result_directory, "stress_curve"),
        header="loading_measure,nominal_stress,cauchy_stress")

    cauchy_norm = np.linalg.norm(response[:, 11:20], axis=1)
    maximum_cauchy_norm = np.max(cauchy_norm)
    if maximum_cauchy_norm <= 0.0:
        raise RuntimeError(
            "The effective Cauchy stress is zero in all frames.")
    loaded_frames = cauchy_norm > 1.0e-6 * maximum_cauchy_norm
    maximum_asymmetry = np.max(response[loaded_frames, -2])
    maximum_hill_mandel = np.nanmax(response[:, -1])

    # Columns: peak ratio and time, final ratio, ratio of the separate energy
    # maxima, stress asymmetry, Hill--Mandel residual, and maximum rotation.
    metrics = np.array([[
        energies["peak_ratio"], energies["peak_time"],
        energies["final_ratio"], energies["ratio_of_maxima"],
        maximum_asymmetry, maximum_hill_mandel, rotation]])
    export_to_csv_file(
        metrics, os.path.join(result_directory, "verification_metrics"),
        header=("peak_kinetic_internal_ratio,peak_ratio_pseudo_time,"
                "final_kinetic_internal_ratio,ratio_of_energy_maxima,"
                "maximum_stress_asymmetry,"
                "maximum_hill_mandel_residual,maximum_nodal_rotation"))

    return curve, maximum_hill_mandel


def run_case(gmsh_cell, case_name, component, final_value, parameters,
             output_directories):
    """Build, solve, and post-process one macroscopic load path."""
    print("\nRun {} load case.".format(case_name))
    analysis_root, result_root, vtk_root = output_directories
    analysis_directory = os.path.join(analysis_root, case_name)
    result_directory = os.path.join(result_root, case_name)
    vtk_directory = os.path.join(vtk_root, case_name)
    if not os.path.isdir(analysis_directory):
        os.makedirs(analysis_directory)
    os.chdir(analysis_directory)

    cell = AbaqusRVE(gmsh_cell, custom_types={1: "B31"})
    assign_section(
        cell, parameters["radius"], parameters["youngs_modulus"],
        parameters["poissons_ratio"], parameters["density"])

    step_name = "LOAD"
    time_increment = parameters["time_increment"]
    cell.model.ImplicitDynamicsStep(
        name=step_name, previous="Initial", application=QUASI_STATIC,
        nlgeom=ON, timePeriod=1.0, maxNumInc=8000,
        initialInc=time_increment, minInc=1.0e-7, maxInc=time_increment)

    def load_path(pseudo_time):
        """Evaluate the macroscopic displacement gradient."""
        gradient = np.zeros((3, 3))
        gradient[component] = final_value * pseudo_time
        return gradient

    load_history = LoadHistory(np.asarray([0.0, 1.0]), load_path)
    cell.apply_periodic_bc(step_name, load_history)
    print("  Run Abaqus analysis.")
    sys.stdout.flush()
    cell.run_analysis(history_outputs=["ALLIE", "ALLKE"])

    print("  Post-process effective response.")
    sys.stdout.flush()
    response = evaluate_response(
        cell, step_name, load_path, component,
        parameters["power_tolerance"])
    if not np.isclose(response[-1, 0], 1.0):
        raise RuntimeError(
            "The {} case stopped at pseudo-time {}; expected 1.0."
            .format(case_name, response[-1, 0]))

    rotation = maximum_rotation(cell, step_name)
    energies = energy_ratios(cell, step_name)
    curve, maximum_hill_mandel = export_results(
        result_directory, response, component, energies, rotation)

    print("  Export VTK results.")
    sys.stdout.flush()
    cell.export_to_vtk(
        vtk_directory, field_outputs=["U", "UR"],
        element_sets=["OCTET_BEAMS"], clear=True)

    print("  Results:")
    print("  final loading measure    : {:.8e}".format(curve[-1, 0]))
    print("  final nominal stress     : {:.8e}".format(curve[-1, 1]))
    print("  final Cauchy stress      : {:.8e}".format(curve[-1, 2]))
    print("  peak ALLKE/ALLIE         : {:.3e}".format(
        energies["peak_ratio"]))
    print("  maximum Hill-Mandel error: {:.3e}".format(
        maximum_hill_mandel))
    print("  maximum nodal rotation   : {:.8e}".format(rotation))


def run_cell(cells_per_axis, elements_per_strut, edge_length,
             imperfection_amplitude, parameters, load_cases,
             output_directories, buckling_directory):
    """Build one cell size and run all prescribed load cases."""
    model_name = "RVE"
    # Regenerate the same perfect mesh used by the corresponding buckling
    # analysis; the mode-file coordinates verify this compatibility.
    create_geometry(
        model_name, edge_length, elements_per_strut, cells_per_axis)
    gmsh_cell = GmshRVE(model_name)
    gmsh_cell.add_periodic_mesh_constraints()
    gmsh_cell.generate_mesh()
    gmsh_cell.build_node_sets()

    # The selected translational eigenmode perturbs the nodal positions once
    # and the resulting imperfect mesh is shared by all three load cases.
    periodic_residual = apply_eigenmode_imperfection(
        gmsh_cell, buckling_directory, imperfection_amplitude)
    print("\n{} x {} x {} Octet imperfection:".format(
        cells_per_axis, cells_per_axis, cells_per_axis))
    print("  amplitude           : {:.8e}".format(
        imperfection_amplitude))
    print("  periodicity residual: {:.3e}".format(periodic_residual))

    for case in load_cases:
        run_case(
            gmsh_cell, case[0], case[1], case[2], parameters,
            output_directories)


def main(include_supercell=True):
    """Run all finite-strain paths for the primitive and supercell meshes."""
    original_directory = os.getcwd()
    try:
        # Material and geometry (all quantities are nondimensional)
        edge_length = 1.0
        beam_radius = 0.04
        imperfection_ratio = 0.01
        parameters = {
            "radius": beam_radius,
            "youngs_modulus": 100.0,
            "poissons_ratio": 0.3,
            "density": 2.5e-7,
            "time_increment": 0.0025,
            "power_tolerance": 1.0e-8,
        }

        # Mesh, loading, and output settings
        elements_per_strut = 16
        load_cases = (
            ("compression", (0, 0), -0.40),
            ("tension", (0, 0), 0.40),
            ("shear_12", (0, 1), 0.40),
        )

        imperfection_amplitude = imperfection_ratio * beam_radius

        # Primitive-cell analyses reported throughout the example
        primitive_outputs = (
            os.path.join(here, "abq"),
            os.path.join(here, "results"),
            os.path.join(here, "vtk_output"),
        )
        run_cell(
            1, elements_per_strut, edge_length,
            imperfection_amplitude, parameters, load_cases,
            primitive_outputs,
            os.path.join(here, "results", "buckling"))

        if include_supercell:
            # Identical load paths on the conforming 2 x 2 x 2 supercell
            supercell_outputs = (
                os.path.join(here, "supercell_abq"),
                os.path.join(here, "supercell_results"),
                os.path.join(here, "supercell_vtk_output"),
            )
            buckling_tag = "buckling_2x2x2_n{}".format(
                elements_per_strut)
            run_cell(
                2, elements_per_strut,
                edge_length, imperfection_amplitude, parameters, load_cases,
                supercell_outputs,
                os.path.join(
                    here, "supercell_results", buckling_tag))

        print("*** Finished finite-strain Octet example ***")
    finally:
        os.chdir(original_directory)
        if gmsh.is_initialized():
            gmsh.finalize()


if __name__ == "__main__":
    # Abaqus replaces stdout; restore the shell that launched the example.
    if sys.__stdout__ is not None:
        sys.stdout = sys.__stdout__
    main(include_supercell=True)
