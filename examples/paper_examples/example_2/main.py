def assign_section(unit_cell, radius, c10, d1, density):
    """Assign a compressible Neo-Hookean circular beam section."""
    material = unit_cell.model.Material(name="OCTET_MATERIAL")
    material.Hyperelastic(
        materialType=ISOTROPIC, testData=OFF, type=NEO_HOOKE,
        volumetricResponse=VOLUMETRIC_DATA, table=((c10, d1),))
    material.Density(table=((density,),))
    unit_cell.assign_beam_section(
        "OCTET_BEAMS", "OCTET_MATERIAL", radius, pre_integrate=False)


def frame_times(unit_cell, step_name):
    """Return all output-frame times."""
    unit_cell.open_odb_file()
    try:
        return [frame.frameValue
                for frame in unit_cell.odb.steps[step_name].frames]
    finally:
        unit_cell.close_odb_file()


def maximum_rotation(unit_cell, step_name):
    """Return the maximum final nodal rotation magnitude."""
    unit_cell.open_odb_file()
    try:
        output = unit_cell.odb.steps[step_name].frames[-1].fieldOutputs
        instance = unit_cell.odb.rootAssembly.instances[unit_cell.model_name]
        values = output["UR"].getSubset(region=instance).values
        return max(np.linalg.norm(np.asarray(value.data, dtype=float))
                   for value in values)
    finally:
        unit_cell.close_odb_file()


def energy_ratios(unit_cell, step_name):
    """Return peak, final, and global kinetic-energy ratios."""
    unit_cell.open_odb_file()
    try:
        step = unit_cell.odb.steps[step_name]
        for region in step.historyRegions.values():
            outputs = region.historyOutputs
            if "ALLIE" not in outputs or "ALLKE" not in outputs:
                continue
            internal = dict(outputs["ALLIE"].data)
            kinetic = dict(outputs["ALLKE"].data)
            records = [(time, internal[time], kinetic[time])
                       for time in sorted(set(internal) & set(kinetic))]
            threshold = 0.02*records[-1][0]
            ratios = [(time, abs(ke)/max(abs(ie), 1.0e-30))
                      for time, ie, ke in records if time >= threshold]
            peak_time, peak_ratio = max(ratios,
                                        key=lambda item: item[1])
            final_ratio = ratios[-1][1]
            global_ratio = (max(abs(ke) for _, _, ke in records)
                            / max(abs(ie) for _, ie, _ in records))
            return peak_ratio, peak_time, final_ratio, global_ratio
    finally:
        unit_cell.close_odb_file()
    raise RuntimeError("ALLIE and ALLKE are unavailable in the ODB.")


def evaluate_response(unit_cell, step_name, load_path, loading_measure,
                      power_tolerance=1.0e-8):
    """Evaluate effective stresses and discrete Hill--Mandel residuals."""
    response = []
    unit_cell.open_odb_file()
    try:
        step = unit_cell.odb.steps[step_name]
        instance = unit_cell.odb.rootAssembly.instances[unit_cell.model_name]
        node_coordinates = {
            node.label: np.asarray(node.coordinates, dtype=float)
            for node in instance.nodes}
        volume = unit_cell.get_volume()

        for frame in step.frames:
            gradient = load_path(frame.frameValue)
            deformation_gradient = np.eye(3) + gradient
            outputs = frame.fieldOutputs

            forces = {}
            for component in range(3):
                for value in outputs[
                        "NFORC{}".format(component + 1)].values:
                    if value.elementLabel is None:
                        continue
                    key = (value.elementLabel, value.nodeLabel)
                    if key not in forces:
                        forces[key] = np.zeros(3)
                    forces[key][component] = value.data

            nominal_stress = np.zeros((3, 3))
            for (_, node_label), force in forces.items():
                nominal_stress += np.outer(
                    force, node_coordinates[node_label])
            nominal_stress *= -1.0/volume

            jacobian = np.linalg.det(deformation_gradient)
            cauchy_stress = (nominal_stress.dot(
                deformation_gradient.T)/jacobian)
            scale = max(np.linalg.norm(cauchy_stress), 1.0e-30)
            asymmetry = np.linalg.norm(
                cauchy_stress - cauchy_stress.T)/scale
            response.append(np.concatenate((
                [frame.frameValue, loading_measure(gradient)],
                nominal_stress.reshape(-1), cauchy_stress.reshape(-1),
                [asymmetry, np.nan])))
    finally:
        unit_cell.close_odb_file()

    response = np.asarray(response)
    for frame_index in range(1, len(response)):
        current_gradient = load_path(response[frame_index, 0])
        previous_gradient = load_path(response[frame_index - 1, 0])
        increment = current_gradient - previous_gradient
        nominal_stress = response[frame_index, 2:11].reshape((3, 3))
        macroscopic_work = float(np.sum(nominal_stress*increment))
        microscopic_work = unit_cell.average_virtual_power(
            step_name, frame=frame_index)
        response[frame_index, -1] = hill_mandel_residual(
            macroscopic_work, microscopic_work, power_tolerance)

    return response


def run_case(gmsh_unit_cell, case_name, load_history, load_path,
             loading_measure, component, parameters, result_tag):
    """Build, solve, and post-process one macroscopic load path."""
    analysis_directory = os.path.join(
        here, result_tag + "_abq", case_name)
    if not os.path.isdir(analysis_directory):
        os.makedirs(analysis_directory)
    os.chdir(analysis_directory)

    unit_cell = AbaqusRVE(
        gmsh_unit_cell, custom_types={1: "B31"}, remove_secondary=True)
    assign_section(unit_cell, parameters["radius"], parameters["c10"],
                   parameters["d1"], parameters["density"])

    step_name = "LOAD"
    unit_cell.model.ImplicitDynamicsStep(
        name=step_name, previous="Initial", application=QUASI_STATIC,
        nlgeom=ON, timePeriod=parameters["step_duration"], maxNumInc=8000,
        initialInc=parameters["time_increment"],
        minInc=1.0e-7*parameters["step_duration"],
        maxInc=parameters["time_increment"])
    unit_cell.apply_periodic_BC(step_name, load_history)
    unit_cell.run_analysis(
        field_outputs=["S"],
        history_outputs=["ALLIE", "ALLKE", "ALLVD", "ALLWK"])

    times = frame_times(unit_cell, step_name)
    if not np.isclose(times[-1], parameters["step_duration"]):
        raise RuntimeError(
            "The {} case stopped at time {}; expected {}.".format(
                case_name, times[-1], parameters["step_duration"]))

    response = evaluate_response(
        unit_cell, step_name, load_path, loading_measure)
    rotation = maximum_rotation(unit_cell, step_name)
    energies = energy_ratios(unit_cell, step_name)

    result_directory = os.path.join(
        here, result_tag + "_results", case_name)
    if not os.path.isdir(result_directory):
        os.makedirs(result_directory)
    export_to_csv_file(response,
                       os.path.join(result_directory, "full_response"))

    stress_index = 3*component[0] + component[1]
    curve = np.column_stack((
        response[:, 1], response[:, 2 + stress_index],
        response[:, 11 + stress_index]))
    export_to_csv_file(
        curve, os.path.join(result_directory, "stress_curve"))

    peak_ratio, peak_time, final_ratio, global_ratio = energies
    cauchy_norm = np.linalg.norm(response[:, 11:20], axis=1)
    loaded_frames = cauchy_norm > 1.0e-6*np.max(cauchy_norm)
    maximum_asymmetry = np.max(response[loaded_frames, -2])
    maximum_hill_mandel = np.nanmax(response[:, -1])
    metrics = np.array([[
        peak_ratio, peak_time, final_ratio, global_ratio,
        maximum_asymmetry, maximum_hill_mandel, rotation]])
    export_to_csv_file(
        metrics, os.path.join(result_directory, "verification_metrics"))

    unit_cell.export_to_vtk(
        os.path.join(here, result_tag + "_vtk", case_name),
        field_outputs=["U", "UR"], element_sets=["OCTET_BEAMS"],
        clear=True)

    print("\n{}:".format(case_name))
    print("  final loading measure    : {:.8e}".format(curve[-1, 0]))
    print("  final nominal stress     : {:.8e}".format(curve[-1, 1]))
    print("  final Cauchy stress      : {:.8e}".format(curve[-1, 2]))
    print("  peak ALLKE/ALLIE         : {:.3e}".format(peak_ratio))
    print("  maximum Hill-Mandel error: {:.3e}".format(maximum_hill_mandel))
    print("  maximum nodal rotation   : {:.8e}".format(rotation))


