def make_load_path(component, final_value):
    """Return a linear macroscopic displacement-gradient history."""
    def load_path(time):
        gradient = np.zeros((3, 3))
        gradient[component] = final_value*time/step_duration
        return gradient
    return load_path


def axial_stretch(gradient):
    return 1.0 + gradient[0, 0]


def shear_amount(gradient):
    return gradient[0, 1]


load_cases = (
    ("compression", (0, 0), -0.40, axial_stretch),
    ("tension", (0, 0), 0.40, axial_stretch),
    ("shear_12", (0, 1), 0.40, shear_amount),
)

selected_case = os.environ.get("OCTET_LOAD_CASE")
