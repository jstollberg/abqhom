"""Plot all six independent effective Cauchy-stress components.

The data are read from the clean finite-strain Octet results generated by
``main.py``.  Compression is parameterized by positive engineering
compression, while tension and shear use their positive imposed measures.
"""

from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np


HERE = Path(__file__).resolve().parent
RESULTS = HERE / "final_results"
OUTPUT_PNG = HERE / "all_cauchy_stress_components.png"
OUTPUT_PDF = HERE / "all_cauchy_stress_components.pdf"

# The Cauchy tensor occupies columns 11--19 of full_response.csv in row-major
# order.  Only the six independent entries are shown.
COMPONENTS = (
    (r"$\bar{\sigma}_{11}$", 0, 0, "#0072B2", "-"),
    (r"$\bar{\sigma}_{22}$", 1, 1, "#D55E00", "-"),
    (r"$\bar{\sigma}_{33}$", 2, 2, "#009E73", "-"),
    (r"$\bar{\sigma}_{12}$", 0, 1, "#CC79A7", "--"),
    (r"$\bar{\sigma}_{13}$", 0, 2, "#E69F00", "--"),
    (r"$\bar{\sigma}_{23}$", 1, 2, "#56B4E9", "--"),
)

CASES = (
    ("compression", r"(a) Compression", r"Engineering compression $1-\bar{F}_{11}$"),
    ("tension", r"(b) Tension", r"Engineering strain $\bar{F}_{11}-1$"),
    ("shear_12", r"(c) Shear", r"Engineering shear $\bar{F}_{12}$"),
)


def load_response(case):
    """Return the loading measure and the complete Cauchy-stress history."""
    response = np.loadtxt(RESULTS / case / "full_response.csv", delimiter=",")
    measure = response[:, 1]
    if case == "compression":
        measure = 1.0 - measure
    elif case == "tension":
        measure = measure - 1.0
    cauchy = response[:, 11:20].reshape((-1, 3, 3))
    return measure, cauchy


plt.rcParams.update({
    "font.family": "serif",
    "font.size": 9,
    "mathtext.fontset": "stix",
    "axes.linewidth": 0.8,
    "lines.linewidth": 1.45,
})

figure, axes = plt.subplots(1, 3, figsize=(7.25, 2.65))

for axis, (case, title, xlabel) in zip(axes, CASES):
    measure, cauchy = load_response(case)
    for label, row, column, color, linestyle in COMPONENTS:
        axis.plot(
            measure,
            cauchy[:, row, column],
            label=label,
            color=color,
            linestyle=linestyle,
        )
    axis.axhline(0.0, color="0.25", linewidth=0.55, zorder=0)
    axis.set_title(title, pad=4.0)
    axis.set_xlabel(xlabel)
    axis.set_xlim(0.0, 0.4)
    axis.grid(alpha=0.18, linewidth=0.5)
    axis.tick_params(direction="in")

axes[0].set_ylabel(r"Effective Cauchy stress $\bar{\sigma}_{ij}$")

handles, labels = axes[0].get_legend_handles_labels()
figure.legend(
    handles,
    labels,
    loc="upper center",
    bbox_to_anchor=(0.5, 1.015),
    ncol=6,
    frameon=False,
    handlelength=2.2,
    columnspacing=1.15,
)
figure.subplots_adjust(left=0.087, right=0.995, bottom=0.21, top=0.77, wspace=0.32)
figure.savefig(OUTPUT_PNG, dpi=300, bbox_inches="tight")
figure.savefig(OUTPUT_PDF, bbox_inches="tight")

print(OUTPUT_PNG)
print(OUTPUT_PDF)
